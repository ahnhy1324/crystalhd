"""Generate native schema data from the production CLI and reviewed presets.

Committed output permits a native-only build without Python. --check is part of
configuration-check, so changes to either source cannot silently drift.
"""
import importlib.util
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("config_core", str(ROOT / "scripts/crystalhd-config.py"))
core = importlib.util.module_from_spec(spec)
spec.loader.exec_module(core)


def literal(value):
    if value is core.ABSENT:
        return "Value()"
    if value is core.UNSET:
        return "Value::Unset()"
    if type(value) is bool:
        return "Value({0})".format(str(value).lower())
    if type(value) is int:
        return "Value(uint64_t({0}))".format(value)
    return "Value({0})".format(json.dumps(value, ensure_ascii=True))


def generate():
    lines = ["// Generated by scripts/generate-native-config.py; do not edit.",
             "// SPDX-License-Identifier: LGPL-2.1-or-later", "static Rules MakeRules() {", "  Rules rules;"]
    kinds = {"boolean": "Boolean", "nonempty_string": "NonemptyString",
             "any_string": "String", "scale_width": "ScaleWidth", "output_size": "OutputSize"}
    for key, validate in sorted(core.RULES.items()):
        kind = getattr(validate, "native_kind", kinds.get(validate.__name__))
        if kind is None:
            raise ValueError("unmapped native validation kind: " + key)
        choices = ", ".join(literal(v) for v in getattr(validate, "native_choices", ()))
        lines.append('  rules.emplace({0}, Rule{{Kind::{1}, {{{2}}}, {3}}});'.format(
            json.dumps(key), kind, choices, literal(core.NATIVE[key])))
    lines += ["  return rules;", "}", "", "static Presets MakePresets() {", "  Presets presets;"]
    catalog = core.parse_preset_manifest((ROOT / "share/crystalhd/config-presets-v1.json").read_bytes())
    for entry in catalog.entries:
        if entry.status != "SELECTABLE":
            continue
        settings = ", ".join("{{{0}, {1}}}".format(json.dumps(k), literal(v))
                             for k, v in sorted(entry.settings.items()))
        lines.append('  presets.emplace({0}, Preset{{{{{1}}}, {2}}});'.format(
            json.dumps(entry.name), settings, str(bool(entry.required_acknowledgements)).lower()))
    lines += ["  return presets;", "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    output = ROOT / "include/crystalhd-config-schema.h"
    result = generate()
    if sys.argv[1:] == ["--check"]:
        if not output.is_file() or output.read_text(encoding="utf-8") != result:
            sys.exit("native configuration schema is stale; run scripts/generate-native-config.py")
    elif not sys.argv[1:]:
        output.write_text(result, encoding="utf-8")
    else:
        sys.exit("usage: generate-native-config.py [--check]")
